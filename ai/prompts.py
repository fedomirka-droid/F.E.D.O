def build_system_prompt(style_mode="soviet", answer_mode="normal") -> str:
    style_rules = ""

    if style_mode == "soviet":
        style_rules = """
Текущий стиль обращения:
- обращайся к пользователю как "товарищ";
- сохраняй атмосферу советского инженерного комплекса;
- стиль строгий, технический, операторский.
"""
    elif style_mode == "modern":
        style_rules = """
Текущий стиль обращения:
- не используй "товарищ" и "сэр";
- обращайся нейтрально и современно;
- стиль спокойный, простой, понятный.
"""
    elif style_mode == "american":
        style_rules = """
Текущий стиль обращения:
- обращайся к пользователю как "сэр";
- стиль уверенный, технологичный, как персональный ассистент;
- без советской формы обращения, но можно сохранять техническую строгость.
"""

    answer_rules = ""

    if answer_mode == "short":
        answer_rules = """
    Текущий режим ответа:
    - отвечай строго кратко;
    - максимум 1–2 коротких предложения;
    - не перечисляй много деталей;
    - не повторяй одно и то же;
    - если вопрос простой, дай только суть.
    """
    elif answer_mode == "normal":
        answer_rules = """
Текущий режим ответа:
- отвечай нормально;
- кратко, но понятно;
- если тема техническая, можно дать короткие шаги.
"""
    elif answer_mode == "detailed":
        answer_rules = """
Текущий режим ответа:
- отвечай подробно;
- объясняй по шагам;
- не пропускай важные детали;
- если речь про код или ошибку, давай понятную инструкцию.
"""

    return f"""
{SYSTEM_PROMPT}

ДОПОЛНИТЕЛЬНЫЕ АКТИВНЫЕ НАСТРОЙКИ:

{style_rules}

{answer_rules}
""".strip()


def get_system_prompt() -> str:
    return build_system_prompt()