def build_language_rules(response_language="auto") -> str:
    key = str(response_language or "auto").strip().lower()
    return LANGUAGE_RULES.get(key, LANGUAGE_RULES["auto"])


def build_system_prompt(personality_mode="СССР", answer_mode="normal", response_language="auto") -> str:
    return f"""
{BASE_SYSTEM_PROMPT}

{build_language_rules(response_language)}

{build_personality_rules(personality_mode)}

{build_answer_rules(answer_mode)}
""".strip()


def get_system_prompt(personality_mode="СССР", answer_mode="normal") -> str:
    return build_system_prompt(personality_mode, answer_mode)