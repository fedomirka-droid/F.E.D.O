"""
F.E.D.O Core — Sanitizer (v1.5.10, government build)

Последний рубеш для ГОВ-сборки: вырезает нецензурную лексику
из ответов LLM. Модель (даже без режима «Агрессивный») иногда
может выдать слово — в госсборке это недопустимо.

В стандартной сборке фильтр НЕ применяется
(в режиме «Агрессивный» такое поведение предусмотрено).
"""
import re

# Полный список форм (без «хвостов»), чтобы не было ложных
# срабатываний: "сухой" / "сухарь" / "хлеб" остаются как есть.
_WORDS = (
    # RU
    "блятейшн", "блядистый", "блядство", "блядский", "блядская",
    "блядское", "блять", "бляди", "блядь", "блядина", "бля",
    "сука", "суки",
    "долбоеб", "долбоёб", "долбаеб",
    "уебищный", "уебище", "уебок", "уёбок",
    "ебашить", "ебанутый", "ебучий", "ебанько", "ебало",
    "заебись", "заебал", "засранец", "засранка", "заеб", "ебать",
    "хуевина", "хуёвый", "хуевый", "хуёвая", "хуевая", "хуйня",
    "хуйни", "хуило", "хуем", "хуев", "хуевик", "хуёб", "хуе",
    "хуё", "хуя", "хую", "хуй", "херасила", "херня", "хер",
    "пиздюль", "пизды", "пизда",
    "пидорас", "пидор",
    "мудила", "мудак",
    "говнистый", "говнять", "говно", "дерьмовый", "дерьмо",
    "гандон", "гандюка",
    # EN
    "motherfucker", "asshole", "bastard", "fucking",
    "fuck", "shit", "bitch", "cunt", "dickhead",
)

_RE = re.compile(
    r"(?<!\w)(" + "|".join(sorted(_WORDS, key=len, reverse=True)) + r")(?!\w)",
    re.IGNORECASE,
)


def sanitize(text: str) -> str:
    """Заменить нецензурные слова на '****'."""
    if text is None:
        return ""
    s = str(text)
    return _RE.sub("****", s)
